// Builds the site from its sources:
//   src/pages/*.html + the shared layout   ->  site/*.html
//   the Python model's results            ->  site/assets/js/data/*.js (scripts/make_data.py)
//   the Python package itself             ->  site/assets/py/ (run in the browser by Pyodide)
//   Pyodide, three.js and the fonts (npm) ->  site/assets/pyodide, site/assets/vendor, site/assets/fonts
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const python = process.env.PYTHON || 'python3';

// ---------- Generated data ----------
const dataDir = join(root, 'site/assets/js/data');
if (!process.argv.includes('--pages-only')) {
  execFileSync(python, [join(root, 'scripts/make_data.py'), dataDir], { stdio: 'inherit' });
}

// ---------- The Python package, for Pyodide ----------
const pyDir = join(root, 'site/assets/py/tepidline');
rmSync(join(root, 'site/assets/py'), { recursive: true, force: true });
mkdirSync(pyDir, { recursive: true });
const pyFiles = readdirSync(join(root, 'tepidline')).filter((f) => f.endsWith('.py') && f !== '__main__.py' && f !== 'verify.py').sort();
for (const f of pyFiles) copyFileSync(join(root, 'tepidline', f), join(pyDir, f));
mkdirSync(dataDir, { recursive: true });
writeFileSync(join(dataDir, 'pyfiles.js'), `// Generated by scripts/build.mjs. Do not edit by hand.\nexport const PY_FILES = ${JSON.stringify(pyFiles)};\n`);

// ---------- Vendored files ----------
const copies = [
  ['node_modules/three/build/three.module.min.js', 'site/assets/vendor/three.module.min.js'],
  ['node_modules/three/LICENSE', 'site/assets/vendor/three.LICENSE.txt'],
  ['node_modules/pyodide/pyodide.mjs', 'site/assets/pyodide/pyodide.mjs'],
  ['node_modules/pyodide/pyodide.asm.js', 'site/assets/pyodide/pyodide.asm.js'],
  ['node_modules/pyodide/pyodide.asm.wasm', 'site/assets/pyodide/pyodide.asm.wasm'],
  ['node_modules/pyodide/python_stdlib.zip', 'site/assets/pyodide/python_stdlib.zip'],
  ['node_modules/pyodide/pyodide-lock.json', 'site/assets/pyodide/pyodide-lock.json'],
  ['node_modules/@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2', 'site/assets/fonts/figtree-latin.woff2'],
  ['node_modules/@fontsource-variable/figtree/LICENSE', 'site/assets/fonts/figtree.LICENSE.txt'],
  ['node_modules/@fontsource-variable/fraunces/files/fraunces-latin-wght-normal.woff2', 'site/assets/fonts/fraunces-latin.woff2'],
  ['node_modules/@fontsource-variable/fraunces/files/fraunces-latin-wght-italic.woff2', 'site/assets/fonts/fraunces-latin-italic.woff2'],
  ['node_modules/@fontsource-variable/fraunces/LICENSE', 'site/assets/fonts/fraunces.LICENSE.txt'],
];
for (const [from, to] of copies) {
  mkdirSync(dirname(join(root, to)), { recursive: true });
  copyFileSync(join(root, from), join(root, to));
}
writeFileSync(join(root, 'site/assets/pyodide/NOTICE.txt'),
  'Pyodide 0.29.4 (https://github.com/pyodide/pyodide), Mozilla Public License 2.0.\nCPython and its standard library, Python Software Foundation License.\nCopied unchanged from the pyodide npm package.\n');

// ---------- Pages ----------
const CSP = [
  "default-src 'none'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "worker-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');
const NAV = [
  ['index', 'index.html', 'Home'],
  ['check', 'check.html', 'Check a building'],
  ['fix', 'fix.html', 'Plan the fixes'],
  ['method', 'method.html', 'How it works'],
];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const pagesDir = join(root, 'src/pages');
const built = [];
for (const file of readdirSync(pagesDir).filter((f) => f.endsWith('.html')).sort()) {
  const raw = readFileSync(join(pagesDir, file), 'utf8');
  const m = raw.match(/^<!--(\{[\s\S]*?\})-->\n/);
  if (!m) throw new Error(`${file}: missing the JSON header comment`);
  const meta = JSON.parse(m[1]);
  const body = raw.slice(m[0].length);
  const nav = NAV.map(([id, href, label]) => `<a href="${href}"${id === meta.nav ? ' aria-current="page"' : ''}>${label}</a>`).join('\n        ');
  const html = `<!doctype html>
<html lang="en-AU">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="${CSP}">
  <meta name="referrer" content="no-referrer">
  <meta name="color-scheme" content="dark">
  <title>${esc(meta.title)}</title>
  <meta name="description" content="${esc(meta.description)}">
  <link rel="icon" href="assets/icon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/css/site.css">
  <script type="module" src="assets/js/${meta.script}"></script>
</head>
<body class="page-${meta.nav}">
  <a class="skip" href="#main">Skip to the content</a>
  <header class="top">
    <div class="top-inner">
      <a class="mark" href="index.html" aria-label="Tepidline home">
        <svg class="mark-icon" viewBox="0 0 32 32" aria-hidden="true"><path d="M3 9h12a5 5 0 0 1 5 5v15" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round"/><path class="line" d="M23 4c3 4 5 7 5 10a5 5 0 0 1-10 0c0-3 2-6 5-10z" stroke-width="0"/></svg>
        <span>Tepidline</span>
      </a>
      <nav class="nav" aria-label="Pages">
        ${nav}
      </nav>
    </div>
  </header>
  <main id="main">
${body.trimEnd()}
  </main>
  <footer class="foot">
    <div class="foot-inner">
      <p>Tepidline runs in your browser: a plan you load never leaves this device. It screens for the conditions guidelines warn about; it does not test water or measure bacteria. For a building with vulnerable people, follow your water management plan and talk to a licensed plumber.</p>
      <p>Built by Reihaneh Rahmati · <a href="https://github.com/reihooneh/tepidline">Source on GitHub</a></p>
    </div>
  </footer>
</body>
</html>
`;
  writeFileSync(join(root, 'site', file), html);
  built.push(file);
}
console.log(`Built ${built.length} pages (${built.join(', ')}).`);
