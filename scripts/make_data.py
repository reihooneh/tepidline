"""Writes the data the pages start from, using the same Python model they run in the browser.

python3 scripts/make_data.py site/assets/js/data
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tepidline import api, examples, verify


def write(out: Path, name: str, export: str, value: object, what: str) -> None:
    text = json.dumps(value, separators=(",", ":"))
    header = f"// Generated by scripts/make_data.py from {what}. Do not edit by hand.\n"
    (out / name).write_text(f"{header}export const {export} = {text};\n")


def main() -> None:
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    write(out, "home.js", "HOME", api.check("house", {"season": "summer"}), "the example house in summer")
    write(out, "examples.js", "EXAMPLES", {k: f() for k, f in examples.EXAMPLES.items()}, "tepidline/examples.py")
    plans = {}
    for name in examples.EXAMPLES:
        for season in ("summer", "winter"):
            plans[f"{name}-{season}"] = api.plan(name, {"season": season})
            print(f"  planned {name} in {season}", file=sys.stderr)
    write(out, "plans.js", "PLANS", plans, "every combination of fixes for each example and season")
    write(out, "checks.js", "CHECKS", verify.run(), "tepidline/verify.py")


if __name__ == "__main__":
    main()
